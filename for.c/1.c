#include<stdio.h>
int  main()
{
    int i;
    for (i=0; i<=5; i++)
    {
       printf("%d\n",i);
    } 
    for (i=0; i<=5; i++)
    {
       printf("%d\n",i*3);
    } 
    for (i=2; i<=32; i*=2)
    {
       printf("%d\n",i);
    } 
    for (i=5; i>=1; i--)
    {
       printf("%d\n",i);
    } 
return 0;
} 
